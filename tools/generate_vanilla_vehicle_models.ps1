param(
    [string]$OutputRoot = (Join-Path $PSScriptRoot '..\common\src\main\resources\assets\automobility\models\entity\automobile\frame')
)

function Box([int]$X, [int]$Y, [int]$Z, [int]$Width, [int]$Height, [int]$Length, [int]$U, [int]$V) {
    return [ordered]@{
        offset = @($X, $Y, $Z)
        dimensions = @($Width, $Height, $Length)
        uv = @($U, $V)
    }
}

function Save-Model([string]$Id, [array]$Cuboids) {
    $document = [ordered]@{
        texture = [ordered]@{ width = 64; height = 64 }
        bones = [ordered]@{
            main = [ordered]@{
                cuboids = $Cuboids
                children = [ordered]@{}
            }
        }
    }
    $folder = Join-Path $OutputRoot $Id
    New-Item -ItemType Directory -Force -Path $folder | Out-Null
    $document | ConvertTo-Json -Depth 20 | Set-Content -LiteralPath (Join-Path $folder 'main.json') -Encoding UTF8
}

